window.getUnitInfo = function(code) {
  if (!code) return null;
  const upper = code.trim().toUpperCase();
  const found = window.ALL_MASTER_UNITS.find(u => u.code.toUpperCase() === upper);
  if (found) return found;
  if (window.MASTER_UNITS[upper]) {
    return {
      code: upper,
      model: window.MASTER_UNITS[upper],
      category: 'General Fleet'
    };
  }
  return {
    code: upper,
    model: 'Unit Terdaftar',
    category: 'General Fleet'
  };
};

